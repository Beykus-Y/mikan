CREATE TABLE promo_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  type TEXT NOT NULL CHECK (type IN ('days','traffic','percent','fixed')),
  value BIGINT NOT NULL CHECK (value > 0),
  currency TEXT NOT NULL DEFAULT '' CHECK (currency IN ('','XTR','RUB')),
  starts_at BIGINT,
  ends_at BIGINT,
  max_uses BIGINT CHECK (max_uses IS NULL OR max_uses > 0),
  used_count BIGINT NOT NULL DEFAULT 0 CHECK (used_count >= 0),
  per_user_limit BIGINT NOT NULL DEFAULT 1 CHECK (per_user_limit > 0),
  discount_ttl BIGINT NOT NULL DEFAULT 0 CHECK (discount_ttl >= 0),
  min_order BIGINT NOT NULL DEFAULT 0 CHECK (min_order >= 0),
  max_discount BIGINT NOT NULL DEFAULT 0 CHECK (max_discount >= 0),
  tariff_ids TEXT NOT NULL DEFAULT '[]',
  pool_id BIGINT REFERENCES traffic_pools(id) ON DELETE RESTRICT,
  first_purchase_only BIGINT NOT NULL DEFAULT 0 CHECK (first_purchase_only IN (0,1)),
  new_users_only BIGINT NOT NULL DEFAULT 0 CHECK (new_users_only IN (0,1)),
  enabled BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  deleted BIGINT NOT NULL DEFAULT 0 CHECK (deleted IN (0,1)),
  created_at BIGINT NOT NULL,
  created_by BIGINT REFERENCES admins(id) ON DELETE SET NULL
);
